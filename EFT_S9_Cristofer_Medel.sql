    WHEN OTHERS THEN
        RAISE;
END;
/

-- RECHAZA CAMBIOS DE TIPO QUE CONTRADICEN UN SUBTIPO YA REGISTRADO.
-- ADMITE CAMBIAR EL TIPO CUANDO NO EXISTE UN SUBTIPO INCOMPATIBLE.
CREATE OR REPLACE TRIGGER TRABAJADOR_TIPO_TRG
BEFORE UPDATE OF TIPO_TRABAJADOR ON TRABAJADOR
FOR EACH ROW
DECLARE
    V_INCOMPATIBLES NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO V_INCOMPATIBLES
    FROM (
        SELECT NUM_INSCRIPCION
        FROM JUGADOR
        WHERE NUM_INSCRIPCION = :OLD.NUM_INSCRIPCION
          AND :NEW.TIPO_TRABAJADOR <> 'J'
        UNION ALL
        SELECT NUM_INSCRIPCION
        FROM PERSONAL_PLANTA
        WHERE NUM_INSCRIPCION = :OLD.NUM_INSCRIPCION
          AND :NEW.TIPO_TRABAJADOR <> 'P'
    );

    IF V_INCOMPATIBLES > 0 THEN
        RAISE_APPLICATION_ERROR(
            -20002,
            'El tipo de trabajador debe coincidir con el subtipo registrado.'
        );
    END IF;
END;
/



-- VALIDACION: UN JUGADOR PERTENECE A UN SOLO CLUB A LA VEZ
-- FECHA_FIN ES EL ULTIMO DIA DEL PERIODO
-- NULL INDICA UN PERIODO SIN FECHA DE TERMINO

CREATE OR REPLACE TRIGGER HISTORIAL_CLUB_PERIODO_TRG
FOR INSERT OR UPDATE ON HISTORIAL_CLUB
COMPOUND TRIGGER

    BEFORE EACH ROW IS
        V_INSCRIPCION JUGADOR.NUM_INSCRIPCION%TYPE;
    BEGIN
        -- BLOQUEA EL JUGADOR DURANTE EL CAMBIO DE SU HISTORIAL
        SELECT NUM_INSCRIPCION
        INTO V_INSCRIPCION
        FROM JUGADOR
        WHERE NUM_INSCRIPCION = :NEW.NUM_INSCRIPCION
        FOR UPDATE;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            NULL; -- LA CLAVE FORANEA RECHAZARA EL REGISTRO
    END BEFORE EACH ROW;

    AFTER STATEMENT IS
        V_SOLAPAMIENTOS NUMBER;
    BEGIN
        SELECT COUNT(*)
        INTO V_SOLAPAMIENTOS
        FROM HISTORIAL_CLUB A
        JOIN HISTORIAL_CLUB B
          ON A.NUM_INSCRIPCION = B.NUM_INSCRIPCION
         AND A.FECHA_INICIO < B.FECHA_INICIO
        WHERE A.FECHA_FIN IS NULL
           OR B.FECHA_INICIO <= A.FECHA_FIN;

        IF V_SOLAPAMIENTOS > 0 THEN
            RAISE_APPLICATION_ERROR(
                -20001,
                'Un jugador no puede tener periodos de permanencia superpuestos.'
            );
        END IF;
    END AFTER STATEMENT;

END HISTORIAL_CLUB_PERIODO_TRG;
