-- BLOQUE 3: VALIDACION DEL DISCRIMINADOR DE LOS SUBTIPOS

-- VALIDACION DE LOS SUBTIPOS Y DE LOS CAMBIOS DE CATEGORIA

CREATE OR REPLACE TRIGGER ARC_FKARC_1_PERSONAL_PLANTA
BEFORE INSERT OR UPDATE OF NUM_INSCRIPCION ON PERSONAL_PLANTA
FOR EACH ROW
DECLARE
    D VARCHAR2(1);
BEGIN
    SELECT TIPO_TRABAJADOR
    INTO D
    FROM TRABAJADOR
    WHERE NUM_INSCRIPCION = :NEW.NUM_INSCRIPCION
    FOR UPDATE;

    IF D IS NULL OR D <> 'P' THEN
        RAISE_APPLICATION_ERROR(
            -20223,
            'El trabajador debe ser de tipo P para pertenecer al personal de planta.'
        );
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        NULL;
    WHEN OTHERS THEN
        RAISE;
END;
/

CREATE OR REPLACE TRIGGER ARC_FKARC_1_JUGADOR
BEFORE INSERT OR UPDATE OF NUM_INSCRIPCION ON JUGADOR
FOR EACH ROW
DECLARE
    D VARCHAR2(1);
BEGIN
    SELECT TIPO_TRABAJADOR
    INTO D
    FROM TRABAJADOR
    WHERE NUM_INSCRIPCION = :NEW.NUM_INSCRIPCION
    FOR UPDATE;

    IF D IS NULL OR D <> 'J' THEN
